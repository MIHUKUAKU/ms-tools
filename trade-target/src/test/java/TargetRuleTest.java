import java.util.HashMap;
import java.util.Map;
import java.util.List;
import java.nio.file.Files;
import java.nio.file.Path;
import local.tradetarget.TargetRule;
import local.tradetarget.TargetConfig;
import local.tradetarget.PresetOption;
import local.tradetarget.TradePositions;

public class TargetRuleTest {
    private static int checks;
    public static void main(String[] args) throws Exception {
        var good = Map.of("minecraft:unbreaking", 3, "minecraft:efficiency", 3, "minecraft:silk_touch", 1);
        check(TargetRule.matches("minecraft:diamond_pickaxe", good));
        check(!TargetRule.matches("minecraft:iron_pickaxe", good));
        check(!TargetRule.matches("minecraft:diamond_pickaxe", Map.of()));
        for (String key : good.keySet()) {
            var wrong = new HashMap<>(good); wrong.remove(key);
            check(!TargetRule.matches("minecraft:diamond_pickaxe", wrong));
            wrong.put(key, good.get(key) + 1);
            check(!TargetRule.matches("minecraft:diamond_pickaxe", wrong));
        }
        var extra = new HashMap<>(good); extra.put("minecraft:fortune", 3);
        check(!TargetRule.matches("minecraft:diamond_pickaxe", extra));
        var defaultRule = TargetRule.Criteria.defaults();
        var miss = new TargetRule.Offer("minecraft:iron_pickaxe", good, 12);
        var hit = new TargetRule.Offer("minecraft:diamond_pickaxe", good, 12);
        check(defaultRule.findMatch(List.of()) == -1);
        check(defaultRule.findMatch(List.of(miss, hit)) == 1);
        check(defaultRule.findMatch(List.of(hit, miss)) == -1);
        var any = new TargetRule.Criteria(defaultRule.item(), good, false, false, -1, -1, 0, true);
        check(any.findMatch(List.of(hit, miss)) == 0);
        check(any.findMatch(List.of(miss, hit)) == 1);
        var second = new TargetRule.Criteria(defaultRule.item(), good, false, false, -1, -1, 2, true);
        check(second.findMatch(List.of(hit)) == -1);
        check(second.findMatch(List.of(miss, hit)) == 1);
        check(second.findMatch(List.of(hit, miss)) == -1);
        var expensive = new TargetRule.Offer(hit.item(), good, 20);
        var price = new TargetRule.Criteria(hit.item(), good, false, false, 10, 12, 0, false);
        check(price.matches(hit));
        check(price.matches(new TargetRule.Offer(hit.item(), good, 10)));
        check(!price.matches(new TargetRule.Offer(hit.item(), good, 9)));
        check(!price.matches(expensive));
        check(!price.matches(new TargetRule.Offer(hit.item(), good, -1)));
        var exactPrice = new TargetRule.Criteria(hit.item(), good, false, false, 12, 12, 0, true);
        check(exactPrice.matches(hit));
        check(!exactPrice.matches(new TargetRule.Offer(hit.item(), good, 11)));
        var higher = new HashMap<>(good); higher.put("minecraft:efficiency", 5);
        check(!any.matches(new TargetRule.Offer(hit.item(), higher, 12)));
        var atLeast = new TargetRule.Criteria(hit.item(), good, true, false, -1, -1, 0, true);
        check(atLeast.matches(new TargetRule.Offer(hit.item(), higher, 12)));
        higher.put("minecraft:unbreaking", 2);
        check(!atLeast.matches(new TargetRule.Offer(hit.item(), higher, 12)));
        var extrasAllowed = new TargetRule.Criteria(hit.item(), good, false, true, -1, -1, 0, true);
        check(extrasAllowed.matches(new TargetRule.Offer(hit.item(), extra, 12)));
        check(!any.matches(new TargetRule.Offer(hit.item(), extra, 12)));
        var noEnchantFilter = new TargetRule.Criteria(hit.item(), Map.of(), false, false, -1, -1, 0, true);
        check(noEnchantFilter.matches(hit));
        var wildcard = new TargetRule.Criteria("*", Map.of("minecraft:silk_touch", 1), false, true, -1, -1, 0, true);
        check(wildcard.matches(miss));
        check(wildcard.matches(new TargetRule.Offer("minecraft:enchanted_book", Map.of("minecraft:silk_touch", 1), 8)));
        var mutable = new HashMap<>(good);
        var snapshot = new TargetRule.Criteria(hit.item(), mutable, false, false, -1, -1, 0, true);
        mutable.clear(); check(snapshot.matches(hit));
        java.util.function.UnaryOperator<String> id = name -> name.contains(":") ? name : "minecraft:" + name;
        check(TargetConfig.defaults().parse(id, id).equals(defaultRule));
        check(new TargetConfig("diamond_pickaxe", "unbreaking=3，efficiency=3；silk_touch=1", "12", "12", "任意", false, false, false).parse(id, id).equals(
                new TargetRule.Criteria(hit.item(), good, false, false, 12, 12, 0, false)));
        check(new TargetConfig("diamond_pickaxe", "", "", "", "1", false, true, true).parse(id, id).positions().numbers().equals(java.util.Set.of(1)));
        fails(() -> new TargetConfig("diamond_pickaxe", "unbreaking=3,unbreaking=2", "", "", "any", false, false, true).parse(id, id));
        fails(() -> new TargetConfig("diamond_pickaxe", "unbreaking=three", "", "", "any", false, false, true).parse(id, id));
        fails(() -> new TargetConfig("diamond_pickaxe", "unbreaking=3,", "", "", "any", false, false, true).parse(id, id));
        fails(() -> new TargetConfig("diamond_pickaxe", "", "20", "10", "any", false, false, true).parse(id, id));
        fails(() -> new TargetConfig("diamond_pickaxe", "", "", "65", "any", false, false, true).parse(id, id));
        fails(() -> new TargetConfig("diamond_pickaxe", "", "", "", "-2", false, false, true).parse(id, id));
        fails(() -> new TargetConfig("", "", "", "", "any", false, false, true).parse(id, id));
        fails(() -> new TargetRule.Criteria(hit.item(), Map.of("minecraft:unbreaking", 0), false, false, -1, -1, 0, true));
        var arrowConfig = TargetConfig.arrowPreset();
        check(arrowConfig.potionEffects());
        check(!TargetConfig.bookPreset().potionEffects());
        check(!TargetConfig.defaults().potionEffects());
        check(TargetConfig.bookPreset().item().equals("minecraft:enchanted_book"));
        var arrowRule = arrowConfig.parse(id, name -> { throw new AssertionError("Effects went through enchantment parser"); }, id);
        var slow1 = Map.of("minecraft:slowness", 1);
        var slow2 = Map.of("minecraft:slowness", 2);
        var arrow = new TargetRule.Offer("minecraft:tipped_arrow", Map.of(), 2, slow1);
        check(arrowRule.matches(arrow));
        check(!arrowRule.matches(new TargetRule.Offer("minecraft:arrow", Map.of(), 2, slow1)));
        check(!arrowRule.matches(new TargetRule.Offer("minecraft:tipped_arrow", slow1, 2, Map.of())));
        check(!arrowRule.matches(new TargetRule.Offer("minecraft:tipped_arrow", Map.of(), 2, Map.of("minecraft:poison", 1))));
        check(!arrowRule.matches(new TargetRule.Offer("minecraft:tipped_arrow", Map.of(), 2, slow2)));
        var arrowMinimum = new TargetRule.Criteria("minecraft:tipped_arrow", slow1, true, true, 1, 2, 0, true, true);
        check(arrowMinimum.matches(new TargetRule.Offer("minecraft:tipped_arrow", Map.of(), 2, slow2)));
        check(!arrowMinimum.matches(new TargetRule.Offer("minecraft:tipped_arrow", Map.of(), 3, slow1)));
        check(!arrowMinimum.matches(new TargetRule.Offer("minecraft:tipped_arrow", Map.of(), -1, slow1)));
        check(arrowRule.findMatch(List.of(hit, arrow)) == 1);
        var arrowLast = new TargetRule.Criteria("minecraft:tipped_arrow", slow1, false, true, -1, -1, -1, true, true);
        check(arrowLast.findMatch(List.of(arrow, hit)) == -1);
        check(arrowLast.findMatch(List.of(hit, arrow)) == 1);
        var multiEffect = new HashMap<>(slow1); multiEffect.put("minecraft:poison", 1);
        var arrowStrict = new TargetRule.Criteria("minecraft:tipped_arrow", slow1, false, false, -1, -1, 0, true, true);
        check(!arrowStrict.matches(new TargetRule.Offer("minecraft:tipped_arrow", Map.of(), 2, multiEffect)));
        check(arrowRule.matches(new TargetRule.Offer("minecraft:tipped_arrow", Map.of(), 2, multiEffect)));
        // Enchantment metadata on the arrow must not affect strict potion matching.
        check(arrowStrict.matches(new TargetRule.Offer("minecraft:tipped_arrow", good, 2, slow1)));
        // Potion metadata must not fulfill a book's enchantment condition.
        var bookRule = TargetConfig.bookPreset().parse(id, id);
        var mending = Map.of("minecraft:mending", 1);
        check(bookRule.matches(new TargetRule.Offer("minecraft:enchanted_book", mending, 10)));
        check(!bookRule.matches(new TargetRule.Offer("minecraft:enchanted_book", Map.of(), 10, mending)));
        fails(() -> arrowConfig.parse(id, id));
        fails(() -> new TargetRule.Criteria("minecraft:diamond_pickaxe", slow1, false, false, -1, -1, 0, true, true));
        var chineseArrow = new TargetConfig("药水箭", "缓慢=2", "1", "3", "任意", false, true, true, true);
        check(chineseArrow.parse(name -> "minecraft:tipped_arrow", id, name -> "minecraft:slowness").enchantments().equals(slow2));
        check(PresetOption.compactLevels(List.of(1)).equals("I"));
        check(PresetOption.compactLevels(List.of(1, 2, 3, 4, 5)).equals("I–V"));
        check(PresetOption.compactLevels(List.of(1, 4, 6)).equals("I, IV, VI"));
        check(PresetOption.compactLevels(List.of(5, 4, 3, 3, 2, 1)).equals("I–V"));
        check(PresetOption.compactLevels(List.of(1, 2, 5, 6, 10)).equals("I–II, V–VI, X"));
        check(PresetOption.roman(20).equals("20"));
        var efficiencyOption = new PresetOption("minecraft:efficiency", "效率", "Efficiency", List.of(1, 2, 3, 4, 5));
        check(efficiencyOption.label().equals("效率 / Efficiency (I–V)"));
        check(efficiencyOption.contains("效率"));
        check(efficiencyOption.contains("EFFICIENCY"));
        check(efficiencyOption.contains("minecraft:eff"));
        check(efficiencyOption.contains("  eff  "));
        check(!efficiencyOption.contains("slowness"));
        check(efficiencyOption.condition(5).equals("minecraft:efficiency=5"));
        fails(() -> efficiencyOption.condition(6));
        fails(() -> new PresetOption("x", "x", "x", List.of()));
        fails(() -> new PresetOption("x", "x", "x", List.of(0)));
        var sparse = new PresetOption("minecraft:slowness", "缓慢", "Slowness", List.of(6, 1, 4, 1));
        check(sparse.levels().equals(List.of(1, 4, 6)));
        check(sparse.nextLevel(1, 1) == 4);
        check(sparse.nextLevel(6, -1) == 4);
        check(sparse.nextLevel(1, -1) == 1);
        check(sparse.nextLevel(6, 1) == 6);
        check(sparse.nextLevel(2, 1) == 1);
        fails(() -> sparse.condition(2));
        var positions = TradePositions.parse("2,5,8");
        check(positions.numbers().equals(java.util.Set.of(2, 5, 8)));
        check(positions.serialize().equals("2,5,8"));
        check(positions.includes(5, 10));
        check(!positions.includes(4, 10));
        check(!positions.includes(8, 6));
        check(!positions.includes(0, 10));
        check(TradePositions.parse("8，2,5,2").serialize().equals("2,5,8"));
        check(TradePositions.parse("任意").resolve(4).equals(java.util.Set.of(1, 2, 3, 4)));
        check(TradePositions.parse("last").resolve(4).equals(java.util.Set.of(4)));
        check(TradePositions.parse("最后").includes(6, 6));
        check(TradePositions.parse("any").includes(7, 7));
        check(TradePositions.parse("none").isEmpty());
        check(TradePositions.parse("2,8").resolve(4).equals(java.util.Set.of(2, 8)));
        fails(() -> TradePositions.parse("2,"));
        fails(() -> TradePositions.parse("2,0"));
        fails(() -> TradePositions.parse("2,-1"));
        fails(() -> TradePositions.parse("1001"));
        fails(() -> TradePositions.parse("2,x"));
        fails(() -> new TargetRule.Criteria(hit.item(), good, false, false, -1, -1, TradePositions.parse("none"), true, false));
        var multi = new TargetRule.Criteria(hit.item(), good, false, false, -1, -1, TradePositions.parse("2,4"), true, false);
        check(multi.findMatch(List.of(hit, miss, hit, miss)) == -1);
        check(multi.findMatch(List.of(hit, hit, miss, miss)) == 1);
        check(multi.findMatch(List.of(hit, miss, miss, hit)) == 3);
        check(multi.findMatch(List.of(miss, hit, miss, hit)) == 1);
        check(multi.findMatch(List.of(hit)) == -1);
        var multiConfig = new TargetConfig("diamond_pickaxe", "unbreaking=3,efficiency=3,silk_touch=1", "", "", "2,4", false, false, true);
        check(multiConfig.parse(id, id).equals(multi));
        Path dir = Files.createDirectory(Path.of(args[0]).resolve("config-test-" + Long.toUnsignedString(System.nanoTime())));
        Path file = dir.resolve("settings.properties");
        try {
            check(TargetConfig.load(file).equals(TargetConfig.defaults()));
            var config = new TargetConfig("附魔书", "经验修补=1", "1", "20", "任意", true, true, false);
            config.save(file); check(TargetConfig.load(file).equals(config));
            TargetConfig.defaults().save(file); check(TargetConfig.load(file).equals(TargetConfig.defaults()));
            arrowConfig.save(file); check(TargetConfig.load(file).equals(arrowConfig));
            check(TargetConfig.load(file).parse(id, id, id).matches(arrow));
            TargetConfig.bookPreset().save(file); check(!TargetConfig.load(file).potionEffects());
            // Simulate an old 1.1 properties file without the new mode key.
            Files.writeString(file, "item=minecraft:diamond_pickaxe\nenchantments=unbreaking=3,efficiency=3,silk_touch=1\nposition=last\n");
            check(!TargetConfig.load(file).potionEffects());
            check(TargetConfig.load(file).parse(id, id).equals(TargetRule.Criteria.defaults()));
            multiConfig.save(file); check(TargetConfig.load(file).equals(multiConfig));
            check(TargetConfig.load(file).parse(id, id).findMatch(List.of(miss, hit)) == 1);
        } finally { Files.deleteIfExists(file); Files.deleteIfExists(dir); }
        System.out.println(checks + " matching, parsing, price, position and config persistence checks passed");
    }
    private static void check(boolean condition) { checks++; if (!condition) throw new AssertionError("Check " + checks); }
    private static void fails(Runnable action) {
        try { action.run(); } catch (IllegalArgumentException expected) { checks++; return; }
        throw new AssertionError("Expected rejection");
    }
}
